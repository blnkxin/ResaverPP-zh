#!/usr/bin/env python3
"""Collect the code points used by the (Chinese) UI strings and write src/gui/UiGlyphs.h.

Run after translating the sources. main.cpp merges these glyphs into the UI font so the
Chinese text renders even on a Windows whose ANSI code page is not 936.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "gui" / "UiGlyphs.h"

def sources() -> list:
    """Every source file under src/: a whitelist went stale silently (Bsa.cpp, Save.cpp, Quests.cpp and
    AppQuests.cpp were translated but never scanned), and new upstream files are easy to forget."""
    return sorted(str(p.relative_to(ROOT)).replace("\\", "/") for p in (ROOT / "src").rglob("*") if p.suffix in (".cpp", ".h"))


# ranges the base UI font usually lacks that Chinese text needs
EXTRA = list(range(0x3000, 0x3040)) + list(range(0xFF01, 0xFF5F)) + list(range(0x2000, 0x2070))
KEEP_BELOW = 0x2000   # Latin, Greek, Cyrillic etc. come from the base font


def main() -> None:
    cps = set(EXTRA)
    for rel in sources():
        p = ROOT / rel
        if not p.exists():
            print("missing", rel)
            continue
        text = p.read_text(encoding="utf-8", errors="replace")
        for ch in text:
            cp = ord(ch)
            if cp >= KEEP_BELOW and cp <= 0xFFFF:
                cps.add(cp)
    # don't pull in Cyrillic/Greek/etc. that the base font already covers
    cps = {c for c in cps if not (0x0370 <= c <= 0x052F or 0x1E00 <= c <= 0x1EFF)}
    ordered = sorted(cps)

    ranges = []
    for cp in ordered:
        if ranges and cp == ranges[-1][1] + 1:
            ranges[-1][1] = cp
        else:
            ranges.append([cp, cp])

    lines = [
        "// Generated by i18n/gen_glyph_ranges.py - code points used by the Chinese UI text.",
        "// Do not edit by hand: re-run the script after changing the UI strings.",
        "#pragma once",
        "",
        "// sorted, non-overlapping ranges; terminated by 0",
        "static const unsigned kUiGlyphRanges[] = {",
    ]
    row = []
    for lo, hi in ranges:
        row.append(f"0x{lo:04X}, 0x{hi:04X},")
        if len(row) == 6:
            lines.append("\t" + " ".join(row))
            row = []
    if row:
        lines.append("\t" + " ".join(row))
    lines.append("\t0")
    lines.append("};")
    lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"glyphs={len(ordered)} ranges={len(ranges)} -> {OUT} ({OUT.stat().st_size} bytes)")

    # report characters outside the BMP (would be dropped)
    outside = {cp for cp in cps if cp > 0xFFFF}
    if outside:
        print("dropped non-BMP:", outside)


if __name__ == "__main__":
    main()
